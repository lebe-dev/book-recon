package ru.tinyops.android.bookrecon.storage.settings

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.nio.ByteBuffer
import java.security.GeneralSecurityException
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/** Encrypts small secrets, such as a password, for storage on disk. */
interface SecretCipher {
    fun encrypt(plain: ByteArray): ByteArray

    /** Throws [GeneralSecurityException] when [sealed] is malformed, tampered or from another key. */
    fun decrypt(sealed: ByteArray): ByteArray
}

/**
 * AES-GCM with a random 12-byte IV per encryption. The sealed form is
 * `version (1 byte) | IV (12 bytes) | ciphertext with the 16-byte tag`.
 *
 * @param key supplies the key on every call, so a Keystore key is created only when a secret
 *   is first stored or read.
 */
class AesGcmCipher(private val key: () -> SecretKey) : SecretCipher {
    override fun encrypt(plain: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        // The IV is generated by the cipher: Android Keystore keys refuse caller-provided IVs.
        cipher.init(Cipher.ENCRYPT_MODE, key())
        val iv = cipher.iv
        if (iv.size != IV_SIZE) throw GeneralSecurityException("unexpected IV size ${iv.size}")
        val sealed = cipher.doFinal(plain)
        return ByteBuffer.allocate(1 + IV_SIZE + sealed.size)
            .put(VERSION)
            .put(iv)
            .put(sealed)
            .array()
    }

    override fun decrypt(sealed: ByteArray): ByteArray {
        if (sealed.size < 1 + IV_SIZE + TAG_BITS / 8) throw GeneralSecurityException("sealed secret is too short")
        if (sealed[0] != VERSION) throw GeneralSecurityException("unknown sealed secret version ${sealed[0]}")
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(TAG_BITS, sealed, 1, IV_SIZE))
        return cipher.doFinal(sealed, 1 + IV_SIZE, sealed.size - 1 - IV_SIZE)
    }

    private companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val VERSION: Byte = 1
        const val IV_SIZE = 12
        const val TAG_BITS = 128
    }
}

/** AES keys kept in Android Keystore: the key material never leaves secure hardware. */
object KeystoreKeys {
    private const val PROVIDER = "AndroidKeyStore"

    /** The AES-256 GCM key under [alias], created on first use. */
    @Synchronized
    fun aesKey(alias: String): SecretKey {
        val keyStore = KeyStore.getInstance(PROVIDER).apply { load(null) }
        (keyStore.getKey(alias, null) as? SecretKey)?.let { return it }
        val spec = KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .build()
        return KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
            .apply { init(spec) }
            .generateKey()
    }
}
